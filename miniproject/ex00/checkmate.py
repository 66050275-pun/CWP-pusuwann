#!/usr/bin/env python3

def print_grid(grid):
    """
    ฟังก์ชันช่วยพิมพ์กระดาน (2D List) ให้ออกมาเป็นรูปแบบตารางสวยงามเหมือนในโจทย์
    
    [คำอธิบายฟังก์ชันในส่วนนี้]:
    - enumerate(grid): ฟังก์ชันวนลูปที่ให้ค่า 2 อย่างพร้อมกันเสมอคือ:
        1. i   -> เลขลำดับแถว (เริ่มนับจาก 0, 1, 2, ...)
        2. row -> ข้อมูลในแถวนั้นๆ (เช่น ['R', '.', '.', '.'])
      ช่วยให้เราเช็กได้ว่า แถวไหนคือแถวแรก (i == 0) หรือแถวสุดท้าย (i == len - 1)
      เพื่อใส่เครื่องหมายก้ามปูเปิด '[' และปิด ']' ให้ตรงช่อง
    """
    print("[", end="")
    for i, row in enumerate(grid):
        if i == 0:
            print(f"{row},")
        elif i == len(grid) - 1:
            print(f" {row}]")
        else:
            print(f" {row},")

def checkmate(board):
    # -------------------------------------------------------------------------
    # ขั้นตอนที่ 1: ตรวจสอบความถูกต้องของข้อมูลที่รับเข้ามา
    # -------------------------------------------------------------------------
    # [คำอธิบายฟังก์ชัน]:
    # - not board: เช็กว่ามีข้อมูลส่งเข้ามาไหม ถ้าเป็นค่าว่าง (None หรือ "") จะไม่ทำงาน
    # - isinstance(board, str): ฟังก์ชันสำหรับเช็กชนิดของตัวแปร (Data Type)
    #   ว่า board เป็นข้อความ (str = string) หรือไม่ ถ้าส่งตัวเลขหรืออย่างอื่นมา จะไม่ทำ
    if not board or not isinstance(board, str):
        print("Error: Empty or invalid board.")
        return

    # [คำอธิบายฟังก์ชัน]:
    # - board.splitlines(): หั่นข้อความยาวๆ ที่มีหลายบรรทัด ให้แยกออกมาเป็น List ของแต่ละแถว
    # - line.strip(): ตัดช่องว่าง/เว้นวรรคส่วนเกินที่อยู่หน้าสุดและหลังสุดของบรรทัดทิ้ง
    # - if line.strip(): กรองเอาเฉพาะบรรทัดที่มีข้อความจริง ไม่เอาบรรทัดว่างๆ
    lines = [line.strip() for line in board.splitlines() if line.strip()]
    if not lines:
        print("Error: Empty board.")
        return

    # -------------------------------------------------------------------------
    # ขั้นตอนที่ 2: ตรวจสอบมิติของกระดาน (Dimension Check)
    # -------------------------------------------------------------------------
    # [คำอธิบายฟังก์ชัน]:
    # - len(lines): ฟังก์ชันนับจำนวน เช่น นับว่ากระดานนี้มีทั้งหมดกี่แถว
    num_rows = len(lines)

    # - enumerate(lines): ดึงลำดับแถว (i) และตัวหนังสือในแถว (row)
    #   ถ้าแถวไหนมีความยาว (len(row)) ไม่เท่ากับจำนวนแถว (num_rows)
    #   แสดงว่ากระดาน "ไม่เป็นสี่เหลี่ยมจัตุรัส" (เช่น 4 แถว แต่บางแถวมีแค่ 3 ตัว)
    for i, row in enumerate(lines):
        if len(row) != num_rows:
            print(f"Error: Invalid dimension (Board is not a square: {num_rows} rows x row {i+1} has {len(row)} cols).")
            return

    # ถ้าผ่านเงื่อนไข แสดงว่ากระดานเป็นสี่เหลี่ยมจัตุรัสแน่นอน (size x size)
    size = num_rows

    # -------------------------------------------------------------------------
    # ขั้นตอนที่ 3: ค้นหาและนับจำนวนกษัตริย์ (King: 'K') บนกระดาน
    # -------------------------------------------------------------------------
    # [คำอธิบายฟังก์ชัน]:
    # - range(size): สร้างลำดับตัวเลขตั้งแต่ 0 จนถึง size - 1 (เช่น range(4) จะได้เลข 0, 1, 2, 3)
    #   ใช้คู่กับ for r in range(size) เพื่อเป็นตัวบอกพิกัด แถว (r) และ หลัก (c)
    king_positions = []
    for r in range(size):
        for c in range(size):
            if lines[r][c] == 'K':
                king_positions.append((r, c)) # บันทึกตำแหน่งที่เจอ King

    # ตรวจสอบตามกฎ: บนกระดานต้องมี King เพียง 1 ตัวเท่านั้น
    if len(king_positions) == 0:
        print("Error: No King found on the board.")
        return
    elif len(king_positions) > 1:
        print(f"Error: King unit exceeds limit (Found {len(king_positions)} Kings, must be exactly 1).")
        return

    # ดึงพิกัดแถว (kr = King Row) และหลัก (kc = King Column) ของ King ออกมา
    kr, kc = king_positions[0]

    # -------------------------------------------------------------------------
    # ขั้นตอนที่ 4: แสดงผลกระดานเริ่มต้น และขนาดของกระดาน
    # -------------------------------------------------------------------------
    # [คำอธิบายฟังก์ชัน]:
    # - list(row): แปลงข้อความ เช่น 'R...' ให้กลายเป็น List แยกตัวอักษร ['R', '.', '.', '.']
    grid = [list(row) for row in lines]
    print_grid(grid)
    print(f"({size}, {size})")

    # -------------------------------------------------------------------------
    # ขั้นตอนที่ 5: คำนวณ Check Range (กระดานจำลองแสดงพื้นที่ที่หมากศัตรูโจมตีได้)
    # -------------------------------------------------------------------------
    # ก๊อปปี้กระดานออกมาอีกชุดหนึ่ง เพื่อเอาไว้แต้มตัว 'X' ในช่องที่โดนโจมตี
    check_board = [list(row) for row in lines]

    def mark_attack(r, c):
        """ฟังก์ชันช่วยแต้มตัว 'X' ลงบนกระดานจำลอง"""
        # แต้ม 'X' เฉพาะช่องที่เป็นช่องว่าง ('.') หรือช่องที่ King ยืนอยู่ ('K')
        # จะไม่แต้มทับหมากศัตรูตัวอื่น เพื่อให้เรามองเห็นตำแหน่งหมากเดิมได้ชัดเจน
        if check_board[r][c] in ('.', 'K'):
            check_board[r][c] = 'X'

    # วนลูปสแกนดูหมากทุกตัวบนกระดาน
    for r in range(size):
        for c in range(size):
            piece = lines[r][c] # ตัวหมากในช่องนี้

            # ----------------------------------------------------------
            # 1. เบี้ย (Pawn: 'P'):
            # กฎ: เบี้ยจะกินเฉียงขึ้นข้างบน 1 ช่อง (แถวลบ 1 -> r - 1)
            # ----------------------------------------------------------
            if piece == 'P':
                p_row = r - 1
                # กินเฉียงซ้าย (c - 1) และเฉียงขวา (c + 1)
                for p_col in (c - 1, c + 1):
                    # เช็กว่าพิกัดเป้าหมายไม่หลุดออกนอกขอบกระดาน
                    if 0 <= p_row < size and 0 <= p_col < size:
                        mark_attack(p_row, p_col)

            # ----------------------------------------------------------
            # 2. เรือ (Rook: 'R') หรือ ควีน (Queen: 'Q'):
            # กฎ: โจมตีเป็นเส้นตรง 4 ทิศ [ขึ้น: (-1, 0), ลง: (1, 0), ซ้าย: (0, -1), ขวา: (0, 1)]
            # ----------------------------------------------------------
            if piece in ('R', 'Q'):
                for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
                    cr, cc = r + dr, c + dc
                    # เดินตรวจทีละช่องเป็นแนวตรงไปเรื่อยๆ จนกว่าจะสุดขอบกระดาน
                    while 0 <= cr < size and 0 <= cc < size:
                        mark_attack(cr, cc)
                        # [การขวางทาง]: ถ้าเจอหมากตัวอื่น (P, B, R, Q, K) แสดงว่าโดนบัง
                        # ให้ break (หยุดเดินในทิศนี้ทันที เพราะกระโดดข้ามไม่ได้)
                        if lines[cr][cc] in ('P', 'B', 'R', 'Q', 'K'):
                            break
                        cr += dr
                        cc += dc

            # ----------------------------------------------------------
            # 3. บิชอป (Bishop: 'B') หรือ ควีน (Queen: 'Q'):
            # กฎ: โจมตีแนวทแยง 4 ทิศ [ทแยงซ้ายบน, ทแยงขวาบน, ทแยงซ้ายล่าง, ทแยงขวาล่าง]
            # ----------------------------------------------------------
            if piece in ('B', 'Q'):
                for dr, dc in [(-1, -1), (-1, 1), (1, -1), (1, 1)]:
                    cr, cc = r + dr, c + dc
                    # เดินตรวจทีละช่องในแนวทแยงไปเรื่อยๆ จนกว่าจะสุดขอบกระดาน
                    while 0 <= cr < size and 0 <= cc < size:
                        mark_attack(cr, cc)
                        # ถ้าเจอหมากตัวอื่นขวางทางไว้ ให้หยุดเดินทันที
                        if lines[cr][cc] in ('P', 'B', 'R', 'Q', 'K'):
                            break
                        cr += dr
                        cc += dc

    # -------------------------------------------------------------------------
    # ขั้นตอนที่ 6: แสดงผล Check Range และสรุปคำตอบ Success / Fail
    # -------------------------------------------------------------------------
    print("Check Range:")
    print_grid(check_board)

    # เช็กว่าจุดที่ King ยืนอยู่ (พิกัด kr, kc) โดนแต้มเป็น 'X' หรือไม่?
    # ถ้าเป็น 'X' แปลว่ามีหมากศัตรูสามารถกิน King ได้ -> Success (รุกสำเร็จ)
    # ถ้ายังเป็น 'K' อยู่ แปลว่าไม่มีใครกินถึง -> Fail (รุกไม่สำเร็จ)
    if check_board[kr][kc] == 'X':
        print("Success")
    else:
        print("Fail")
